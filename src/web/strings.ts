export type StringKey = keyof typeof STRINGS;

export function text(language: Language, key: StringKey, values: Readonly<Record<string, string | number>> = {}): string {
  const template = STRINGS[key][language];
  let said = "", from = 0;
  for (const match of template.matchAll(/\{(\w+)\}/g)) {
    const name = match[1]!, at = match.index;
    if (!(name in values)) continue;
    const value = String(values[name]);
    // Copy rule 5: a space stands between Chinese and Latin text only, so a Chinese name sits against the Chinese words beside it.
    const before = template.slice(from, at);
    said += HAN_SPACE_END.test(before) && HAN_START.test(value) ? before.slice(0, -1) : before;
    said += value;
    from = at + match[0].length;
    if (HAN_LAST.test(value) && HAN_AFTER_SPACE.test(template.slice(from))) from += 1;
  }
  return said + template.slice(from);
}
const HAN_SPACE_END = /\p{Script=Han} $/u;
const HAN_START = /^\p{Script=Han}/u;
const HAN_LAST = /\p{Script=Han}$/u;
const HAN_AFTER_SPACE = /^ \p{Script=Han}/u;

/**
 * A string said with one value drawn apart: the words are split at that value's placeholder, so the view can draw the value as its own
 * element and no word changes.
 */
export function sayAround(say: (key: StringKey, values?: Readonly<Record<string, string | number>>) => string, key: StringKey, values: Readonly<Record<string, string | number>>, drawn: string): readonly [before: string, value: string, after: string] {
  const marker = "\u0000";
  const [before = "", after = ""] = say(key, { ...values, [drawn]: marker }).split(marker);
  return [before, String(values[drawn] ?? ""), after];
}

/** The person's own choice, else the browser's first language where it is one of the page's, else English. */
export function preferredLanguage(stored: string | null, browser: readonly string[]): Language {
  if (stored === "en" || stored === "zh") return stored;
  return browser[0]?.toLowerCase().startsWith("zh") === true ? "zh" : "en";
}
